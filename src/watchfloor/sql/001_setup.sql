-- Watchfloor Snowflake setup. Run once as ACCOUNTADMIN (Snowsight worksheet), or via:
--   python -m watchfloor.load.setup_snowflake

-- ---------- Compute, role, database ----------
CREATE WAREHOUSE IF NOT EXISTS WATCHFLOOR_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS WATCHFLOOR_ROLE;
GRANT USAGE ON WAREHOUSE WATCHFLOOR_WH TO ROLE WATCHFLOOR_ROLE;
-- Grant to whoever runs this script. The double quotes keep the exact case of the user name
-- (trial accounts can have lowercase names, which an unquoted identifier would uppercase).
SET current_user_name = '"' || CURRENT_USER() || '"';
GRANT ROLE WATCHFLOOR_ROLE TO USER IDENTIFIER($current_user_name);

CREATE DATABASE IF NOT EXISTS WATCHFLOOR;
GRANT OWNERSHIP ON DATABASE WATCHFLOOR TO ROLE WATCHFLOOR_ROLE COPY CURRENT GRANTS;

USE ROLE WATCHFLOOR_ROLE;
USE WAREHOUSE WATCHFLOOR_WH;
USE DATABASE WATCHFLOOR;

-- RAW: validated records exactly as ingested (append-only, source of truth for citations)
-- CORE: cleaned/derived views used by detection and the dashboard
-- OPS:  alerts, analyst reports, approvals, rejected records
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS CORE;
CREATE SCHEMA IF NOT EXISTS OPS;

-- ---------- RAW ----------
CREATE TABLE IF NOT EXISTS RAW.AIRCRAFT_POSITIONS (
  RECORD_ID        VARCHAR(32)   NOT NULL,
  SOURCE           VARCHAR(16)   NOT NULL,
  OBSERVED_AT      TIMESTAMP_TZ  NOT NULL,
  INGESTED_AT      TIMESTAMP_TZ  NOT NULL,
  LOADED_AT        TIMESTAMP_TZ  DEFAULT CURRENT_TIMESTAMP(),
  ICAO24           VARCHAR(6)    NOT NULL,
  CALLSIGN         VARCHAR(8),
  ORIGIN_COUNTRY   VARCHAR(64),
  LAT              FLOAT         NOT NULL,
  LON              FLOAT         NOT NULL,
  BARO_ALTITUDE_M  FLOAT,
  ON_GROUND        BOOLEAN,
  SPEED_KTS        FLOAT,
  COURSE_DEG       FLOAT,
  SQUAWK           VARCHAR(4),
  RAW_PAYLOAD      VARCHAR,
  KAFKA_TOPIC      VARCHAR(64),
  KAFKA_PARTITION  INTEGER,
  KAFKA_OFFSET     INTEGER
) CLUSTER BY (TO_DATE(OBSERVED_AT));

CREATE TABLE IF NOT EXISTS RAW.VESSEL_POSITIONS (
  RECORD_ID        VARCHAR(32)   NOT NULL,
  SOURCE           VARCHAR(16)   NOT NULL,
  OBSERVED_AT      TIMESTAMP_TZ  NOT NULL,
  INGESTED_AT      TIMESTAMP_TZ  NOT NULL,
  LOADED_AT        TIMESTAMP_TZ  DEFAULT CURRENT_TIMESTAMP(),
  MMSI             NUMBER(9,0)   NOT NULL,
  SHIP_NAME        VARCHAR(64),
  LAT              FLOAT         NOT NULL,
  LON              FLOAT         NOT NULL,
  SPEED_KTS        FLOAT,
  COURSE_DEG       FLOAT,
  TRUE_HEADING     INTEGER,
  NAV_STATUS       INTEGER,
  RAW_PAYLOAD      VARCHAR,
  KAFKA_TOPIC      VARCHAR(64),
  KAFKA_PARTITION  INTEGER,
  KAFKA_OFFSET     INTEGER
) CLUSTER BY (TO_DATE(OBSERVED_AT));

-- ---------- OPS ----------
CREATE TABLE IF NOT EXISTS OPS.REJECTED_RECORDS (
  REJECTED_AT   TIMESTAMP_TZ,
  TARGET_TOPIC  VARCHAR(64),
  ERRORS        VARCHAR,
  RAW_PAYLOAD   VARCHAR
);

CREATE TABLE IF NOT EXISTS OPS.ALERTS (
  ALERT_ID       VARCHAR(36)   NOT NULL,
  DETECTED_AT    TIMESTAMP_TZ  NOT NULL,
  RULE           VARCHAR(32)   NOT NULL,   -- AIS_GAP | LOITER | RENDEZVOUS | ORBIT | ML_ANOMALY
  TRACK_TYPE     VARCHAR(8)    NOT NULL,   -- VESSEL | AIRCRAFT
  TRACK_ID       VARCHAR(16)   NOT NULL,   -- MMSI or ICAO24
  SCORE          FLOAT,
  EVIDENCE_IDS   ARRAY,                    -- RECORD_IDs that triggered the alert
  DETAILS        VARIANT,
  STATUS         VARCHAR(16)   DEFAULT 'NEW'  -- NEW | DRAFTED | APPROVED | REJECTED
);

CREATE TABLE IF NOT EXISTS OPS.REPORTS (
  REPORT_ID        VARCHAR(36)   NOT NULL,
  ALERT_ID         VARCHAR(36)   NOT NULL,
  DRAFTED_AT       TIMESTAMP_TZ  NOT NULL,
  MODEL            VARCHAR(64),
  DRAFT_MARKDOWN   VARCHAR,
  CITED_IDS        ARRAY,
  GROUNDING_SCORE  FLOAT,                  -- share of claims backed by a valid citation
  REVIEWER         VARCHAR(64),
  DECISION         VARCHAR(16),            -- APPROVED | REJECTED | EDITED
  DECIDED_AT       TIMESTAMP_TZ,
  REVIEW_NOTES     VARCHAR
);

-- ---------- CORE views ----------
CREATE OR REPLACE VIEW CORE.VESSEL_LATEST AS
SELECT *
FROM RAW.VESSEL_POSITIONS
QUALIFY ROW_NUMBER() OVER (PARTITION BY MMSI ORDER BY OBSERVED_AT DESC) = 1;

CREATE OR REPLACE VIEW CORE.AIRCRAFT_LATEST AS
SELECT *
FROM RAW.AIRCRAFT_POSITIONS
QUALIFY ROW_NUMBER() OVER (PARTITION BY ICAO24 ORDER BY OBSERVED_AT DESC) = 1;
